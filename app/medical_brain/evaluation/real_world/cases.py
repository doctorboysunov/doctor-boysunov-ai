from __future__ import annotations

from app.medical_brain.evaluation.real_world.guideline_refs import GUIDELINE_SOURCES, criteria_for
from app.medical_brain.evaluation.real_world.types import ConversationTurn, RealWorldCase


def _case(
    id: str,
    title: str,
    specialty: str,
    source: str,
    profile: str,
    message: str,
    guideline_key: str,
    expert: str,
    primary: str,
    *,
    secondary: list[str] | None = None,
    red_flags: list[str] | None = None,
    emergency: bool = False,
    question_topics: list[str] | None = None,
    forbidden: list[str] | None = None,
    referral: str = "",
    risks: list[str] | None = None,
    hint: str = "",
    follow_up: list[ConversationTurn] | None = None,
) -> RealWorldCase:
    turns = [ConversationTurn(role="user", content=message)]
    if follow_up:
        turns.extend(follow_up)
    return RealWorldCase(
        id=id,
        title=title,
        specialty=specialty,
        source=source,
        patient_profile=profile,
        turns=turns,
        guideline_source=GUIDELINE_SOURCES[guideline_key],
        guideline_criteria=criteria_for(guideline_key),
        expert_review=expert,
        expected_primary=primary,
        expected_secondary=secondary or [],
        expected_red_flags=red_flags or [],
        requires_emergency=emergency,
        expected_first_question_topics=question_topics or [],
        forbidden_questions=forbidden or [],
        expected_referral=referral,
        failure_risks=risks or [],
        improvement_hint=hint,
    )


